import AVFoundation
import CoreHaptics
import QuartzCore
import UIKit

// MARK: - Feedback strength levels

/// Key-feedback strength. The raw value is stored in App Group defaults; missing
/// and unknown values resolve to `.medium`, the feel shipped before levels existed.
public enum KeyboardFeedbackLevel: String, CaseIterable, Sendable {
    case soft
    case medium
    case strong

    public static let defaultValue: KeyboardFeedbackLevel = .medium

    public static func resolve(_ storedValue: String?) -> KeyboardFeedbackLevel {
        storedValue.flatMap(Self.init(rawValue:)) ?? defaultValue
    }

    /// Shown by both the host options and the keyboard tools panel.
    public var displayName: String {
        switch self {
        case .soft: return "弱"
        case .medium: return "适中"
        case .strong: return "强"
        }
    }

    /// Cycle order for the settings rows.
    var next: KeyboardFeedbackLevel {
        switch self {
        case .soft: return .medium
        case .medium: return .strong
        case .strong: return .soft
        }
    }

    /// CoreHaptics transient intensity; medium equals the fixed feel shipped before levels.
    var hapticIntensity: Float {
        switch self {
        case .soft: return 0.3
        case .medium: return 0.55
        case .strong: return 0.85
        }
    }

    var hapticSharpness: Float {
        switch self {
        case .soft: return 0.5
        case .medium: return 0.6
        case .strong: return 0.7
        }
    }

    /// Impact style when CoreHaptics is unavailable; distinct per level so the
    /// fallback still expresses strength.
    var fallbackImpactStyle: UIImpactFeedbackGenerator.FeedbackStyle {
        switch self {
        case .soft: return .soft
        case .medium: return .light
        case .strong: return .heavy
        }
    }

    /// Fallback impact strength for the public `impactOccurred(intensity:)` call.
    var fallbackImpactIntensity: CGFloat {
        switch self {
        case .soft: return 0.4
        case .medium: return 0.7
        case .strong: return 1.0
        }
    }
}

// MARK: - Key feedback preferences (the host app settings and the in-keyboard quick settings share one source)

/// Two independent switches, sound and haptics, plus one strength level per
/// channel, stored once in the App Group UserDefaults:
///  - The host app's "Input options · Key feedback" and the keyboard tools' "Key feedback" read and
///    write the same keys, so a change on either side applies to both (the keyboard process re-reads
///    on its next appearance).
///  - Sound defaults on at medium strength, haptics default off. The silent switch and the
///    extension's Full Access still decide whether a sound plays.
public enum KeyboardFeedbackPreferences {
    public static let soundKey = "keyboard.keySoundEnabled"
    public static let hapticKey = "keyboard.keyHapticEnabled"
    public static let soundLevelKey = "keyboard.keySoundLevel"
    public static let hapticLevelKey = "keyboard.keyHapticLevel"
    public static var defaults: UserDefaults { KeyboardRecipeStore.sharedDefaults() ?? .standard }
    public static var soundEnabled: Bool {
        get { (SharedPreferences.object(forKey: soundKey, in: defaults) as? Bool) ?? true }
        set { SharedPreferences.set(newValue, forKey: soundKey, in: defaults) }
    }
    public static var hapticEnabled: Bool {
        get { (SharedPreferences.object(forKey: hapticKey, in: defaults) as? Bool) ?? false }
        set { SharedPreferences.set(newValue, forKey: hapticKey, in: defaults) }
    }
    public static var soundLevel: KeyboardFeedbackLevel {
        get { KeyboardFeedbackLevel.resolve(SharedPreferences.object(forKey: soundLevelKey, in: defaults) as? String) }
        set { SharedPreferences.set(newValue.rawValue, forKey: soundLevelKey, in: defaults) }
    }
    public static var hapticLevel: KeyboardFeedbackLevel {
        get { KeyboardFeedbackLevel.resolve(SharedPreferences.object(forKey: hapticLevelKey, in: defaults) as? String) }
        set { SharedPreferences.set(newValue.rawValue, forKey: hapticLevelKey, in: defaults) }
    }
}

// MARK: - Key click audio

/// One click asset per level (Resources/KeyFeedback, generated by
/// Tools/KeyFeedbackAssets), loaded once per process; the key path only enqueues.
///
/// The session moves to ambient + mix-with-others only from the untouched default
/// category, so the silent switch stays authoritative and other audio keeps playing.
/// A media-services reset invalidates players and session setup, so the cache is
/// dropped and rebuilt on the next tap.
// Player state is confined to `queue`.
final class KeyboardClickAudio: @unchecked Sendable {
    static let shared = KeyboardClickAudio()

    private init() {
        NotificationCenter.default.addObserver(
            forName: AVAudioSession.mediaServicesWereResetNotification, object: nil, queue: nil
        ) { [weak self] _ in
            guard let self else { return }
            self.queue.async { self.resetAfterMediaServicesLoss() }
        }
    }

    /// All player state is confined to this queue, so the key path takes no lock.
    private let queue = DispatchQueue(label: "app.songyan.keyboard.keyClickAudio", qos: .userInteractive)
    // Confined to `queue`.
    private var players: [KeyboardFeedbackLevel: AVAudioPlayer] = [:]
    /// Levels whose asset failed to load; not retried on every key.
    private var failedLevels: Set<KeyboardFeedbackLevel> = []
    private var sessionConfigured = false

    /// Loads the player ahead of the first key so the key path does no file work.
    func prepare(level: KeyboardFeedbackLevel) {
        queue.async { _ = self.player(level: level) }
    }

    func play(level: KeyboardFeedbackLevel) {
        queue.async { self.playNow(level: level) }
    }

    private func playNow(level: KeyboardFeedbackLevel) {
        guard let player = player(level: level) else { return }
        player.currentTime = 0
        if player.play() { return }
        // A refusing player is usually stale (audio server restarted without a notification).
        players[level] = nil
        self.player(level: level)?.play()
    }

    private func resetAfterMediaServicesLoss() {
        players.removeAll()
        failedLevels.removeAll()
        sessionConfigured = false
    }

    private func player(level: KeyboardFeedbackLevel) -> AVAudioPlayer? {
        if let cached = players[level] { return cached }
        if failedLevels.contains(level) { return nil }
        configureAudioSessionOnce()
        guard let url = Self.assetURL(for: level), let player = try? AVAudioPlayer(contentsOf: url) else {
            failedLevels.insert(level)
            return nil
        }
        player.prepareToPlay()
        players[level] = player
        return player
    }

    private func configureAudioSessionOnce() {
        guard !sessionConfigured else { return }
        sessionConfigured = true
        let session = AVAudioSession.sharedInstance()
        if session.category == .soloAmbient {
            // Only replace the untouched default; keep a category someone else chose.
            try? session.setCategory(.ambient, options: [.mixWithOthers])
        }
    }

    private static func assetURL(for level: KeyboardFeedbackLevel) -> URL? {
        let name = "key-click-\(level.rawValue)"
        // Both targets copy Resources/KeyFeedback as a folder reference.
        return Bundle(for: KeyboardClickAudio.self)
            .url(forResource: name, withExtension: "wav", subdirectory: "KeyFeedback")
    }
}

// MARK: - Shared feedback service

/// Lightweight key-feedback service shared by the host typing area and the keyboard extension (each process holds its own singleton):
///  - Sound plays the level's click asset through `AVAudioPlayer`, because
///    `UIDevice.playInputClick` has no volume and cannot express levels.
///  - Key sound only plays in the keyboard extension process (the host typing area is a plain
///    view); settings previews sound in either process. Haptics work in both.
///  - Haptics: ordinary keys = CoreHaptics transient at the level's intensity, falling back to
///    `UIImpactFeedbackGenerator`; candidate/list selection = selection changed. Impact is throttled
///    to a 25 ms floor, so held backspace matches the repeat-delete rhythm.
///  - Process capability is declared by the host: the keyboard extension sets it from `hasFullAccess`
///    (without Full Access neither sound nor haptics are called); the host app keeps the default.
///  - Lifecycle: preferences are cached in-process and refreshed on appearance or a settings write,
///    so the key path does no I/O; players and generators are created only in `prepare()` or a
///    settings write. Appear/disappear are paired by a session token so a late `onDisappear` from a
///    replaced view does not release what the new view warmed up.
///
/// The simulator cannot verify Taptic; sound and haptics in the extension both need Full Access.
@MainActor
public final class KeyboardFeedbackService {
    public static let shared = KeyboardFeedbackService()

    private static let isKeyboardExtensionProcess = Bundle.main.bundleURL.pathExtension == "appex"

    /// Process-level capability (host app allows everything by default; the extension VC updates it from hasFullAccess).
    private var keyClicksAllowedInProcess = true
    private var hapticsAllowedInProcess = true
    /// Preference cache: the key path never reads UserDefaults.
    private var soundEnabled = KeyboardFeedbackPreferences.soundEnabled
    private var hapticEnabled = KeyboardFeedbackPreferences.hapticEnabled
    private var soundLevel = KeyboardFeedbackPreferences.soundLevel
    private var hapticLevel = KeyboardFeedbackPreferences.hapticLevel
    private var impactGenerator: UIImpactFeedbackGenerator?
    /// The level `impactGenerator` was built for (fallback style/intensity follow the level).
    private var fallbackGeneratorLevel: KeyboardFeedbackLevel?
    private var selectionGenerator: UISelectionFeedbackGenerator?
    /// Key taps go through this when CoreHaptics works; `impactGenerator` is the fallback.
    private let keyHaptics = KeyboardKeyHaptics()
    private var lastImpactAt: CFTimeInterval = 0
    private var lastHighlightAt: CFTimeInterval = 0
    /// Feedback lifecycle session token: begin increments it; end passes back its own token and is
    /// ignored if it no longer matches (a newer view began in the meantime).
    private var lifecycleToken = 0
    /// Minimum impact interval for held delete / very fast typing (40 Hz cap, in line with mature keyboard implementations).
    private static let impactIntervalFloor: CFTimeInterval = 0.025
    /// Minimum interval for crossing items during alternate-key slide selection (about a 33 Hz cap).
    private static let highlightIntervalFloor: CFTimeInterval = 0.03

    private init() {}

    /// Whether this process can emit key sounds and haptics (false for the extension without Full Access; the tools panel uses it to inform the user).
    public var feedbackAvailableInProcess: Bool { keyClicksAllowedInProcess && hapticsAllowedInProcess }

    /// Declares whether this process may use key sound / haptics. The keyboard extension calls it
    /// on appear with `hasFullAccess`; the host app does not need to (allowed by default).
    public func setProcessCapabilities(keyClicksAllowed: Bool, hapticsAllowed: Bool) {
        keyClicksAllowedInProcess = keyClicksAllowed
        hapticsAllowedInProcess = hapticsAllowed
        if !hapticsAllowed { release() }
    }

    /// Re-reads the shared preferences (called once on keyboard appear and after either side toggles a switch).
    public func refreshPreferences() {
        soundEnabled = KeyboardFeedbackPreferences.soundEnabled
        hapticEnabled = KeyboardFeedbackPreferences.hapticEnabled
        soundLevel = KeyboardFeedbackPreferences.soundLevel
        hapticLevel = KeyboardFeedbackPreferences.hapticLevel
        if !hapticEnabled { release() }
    }

    /// Persists the sound level and readies its player (also in the host, for previews).
    public func setSoundLevel(_ level: KeyboardFeedbackLevel) {
        KeyboardFeedbackPreferences.soundLevel = level
        soundLevel = level
        if soundEnabled, keyClicksAllowedInProcess {
            KeyboardClickAudio.shared.prepare(level: level)
        }
    }

    public func setHapticLevel(_ level: KeyboardFeedbackLevel) {
        KeyboardFeedbackPreferences.hapticLevel = level
        hapticLevel = level
    }

    /// One settings-preview tap at `level`. Unlike a real key it also sounds in the host app,
    /// whose settings page has no keyboard to demonstrate the level.
    public func previewKeyFeedback(sound: Bool, haptic: Bool, level: KeyboardFeedbackLevel) {
        if sound, soundEnabled, keyClicksAllowedInProcess {
            KeyboardClickAudio.shared.play(level: level)
        }
        guard haptic, hapticEnabled, hapticsAllowedInProcess else { return }
        playKeyHaptic(level: level)
    }

    /// Light warm-up on keyboard appear: prepares the current level's audio player and the
    /// haptic generators only when enabled and allowed in this process.
    /// Returns this lifecycle's session token, to be handed back to `end(token:)` on disappear.
    @discardableResult
    public func prepare() -> Int {
        lifecycleToken += 1
        if soundEnabled, keyClicksAllowedInProcess {
            KeyboardClickAudio.shared.prepare(level: soundLevel)
        }
        guard hapticEnabled, hapticsAllowedInProcess else { return lifecycleToken }
        keyHaptics.warm()
        if !keyHaptics.isAvailable {
            if impactGenerator == nil || fallbackGeneratorLevel != hapticLevel {
                impactGenerator = UIImpactFeedbackGenerator(style: hapticLevel.fallbackImpactStyle)
                fallbackGeneratorLevel = hapticLevel
            }
            impactGenerator?.prepare()
        }
        if selectionGenerator == nil { selectionGenerator = UISelectionFeedbackGenerator() }
        selectionGenerator?.prepare()
        return lifecycleToken
    }

    /// Ends this lifecycle on keyboard disappear (releases generators; they warm up again on the next appearance).
    /// Only an end matching the current token is handled: a late `onDisappear` from an old view during a
    /// controller/view replacement does not release the new view's warm-up state (the token was superseded by a newer begin).
    /// Passing -1/nil (legacy callers) keeps the original semantics: release unconditionally.
    @discardableResult
    public func end(token: Int? = nil) -> Bool {
        if let token, token != lifecycleToken { return false }
        release()
        return true
    }

    /// The host went to the background with the keyboard still attached: stop the key
    /// haptic engine now rather than after its idle timeout. The next tap restarts it.
    public func stopKeyHaptics() {
        keyHaptics.stop()
    }

    /// Releases generators on keyboard disappear (ends the Taptic session; warm up again on the next appearance).
    public func release() {
        impactGenerator = nil
        fallbackGeneratorLevel = nil
        selectionGenerator = nil
        keyHaptics.stop()
        lastImpactAt = 0
        lastHighlightAt = 0
    }

    /// Feedback at the moment of touch down (like the system keyboard: sound/haptic on touch down, not after release).
    /// The following `keyPressed()` for the same key press does not repeat the feedback.
    public func keyTouchDown() {
        playKeyFeedback()
        pendingTouchDownAt = CACurrentMediaTime()
    }

    /// A `keyPressed()` within this window after touch-down feedback counts as the same key press (no repeated sound).
    private static let touchDownCoalesceWindow: CFTimeInterval = 0.6
    private var pendingTouchDownAt: CFTimeInterval?

    /// One effective key press (an accepted action such as insert/delete/confirm/Chinese-English toggle/page switch).
    public func keyPressed() {
        if let pending = pendingTouchDownAt {
            pendingTouchDownAt = nil
            if CACurrentMediaTime() - pending < Self.touchDownCoalesceWindow { return }
        }
        playKeyFeedback()
    }

    private func playKeyFeedback() {
        playKeyClick(level: soundLevel)
        guard hapticEnabled, hapticsAllowedInProcess else { return }
        let now = CACurrentMediaTime()
        guard now - lastImpactAt >= Self.impactIntervalFloor else { return }
        lastImpactAt = now
        playKeyHaptic(level: hapticLevel)
    }

    private func playKeyClick(level: KeyboardFeedbackLevel) {
        guard soundEnabled, Self.isKeyboardExtensionProcess, keyClicksAllowedInProcess else { return }
        KeyboardClickAudio.shared.play(level: level)
    }

    private func playKeyHaptic(level: KeyboardFeedbackLevel) {
        if keyHaptics.isAvailable {
            keyHaptics.play(level: level)
            return
        }
        if impactGenerator == nil || fallbackGeneratorLevel != level {
            impactGenerator = UIImpactFeedbackGenerator(style: level.fallbackImpactStyle)
            fallbackGeneratorLevel = level
        }
        impactGenerator?.impactOccurred(intensity: level.fallbackImpactIntensity)
        impactGenerator?.prepare()
    }

    /// One candidate selection / candidate page turn / list selection: the same click as keys,
    /// with the lighter selection-changed haptic, keeping behavior consistent.
    public func selectionChanged() {
        playKeyClick(level: soundLevel)
        guard hapticEnabled, hapticsAllowedInProcess else { return }
        if selectionGenerator == nil { selectionGenerator = UISelectionFeedbackGenerator() }
        selectionGenerator?.selectionChanged()
        selectionGenerator?.prepare()
    }

    /// Slide-selection on an alternate key crossing to another item: only the lighter selection haptic, no
    /// click (sounding on every step of the slide would drown out typing; the final commit still goes
    /// through selectionChanged / key feedback). Has a minimum interval so sweeping across options does not burst.
    public func alternateHighlightMoved() {
        guard hapticEnabled, hapticsAllowedInProcess else { return }
        let now = CACurrentMediaTime()
        guard now - lastHighlightAt >= Self.highlightIntervalFloor else { return }
        lastHighlightAt = now
        if selectionGenerator == nil { selectionGenerator = UISelectionFeedbackGenerator() }
        selectionGenerator?.selectionChanged()
        selectionGenerator?.prepare()
    }
}

// MARK: - Key haptics (resident CoreHaptics engine)

/// Light key-tap haptic on a dedicated CoreHaptics engine.
///
/// A resident engine avoids repeated cold starts after short pauses and keeps
/// tap playback off the main thread. It stops after `idleStopDelay` or when the
/// keyboard disappears.
///
/// Fails closed: if the engine cannot be created or started, `isAvailable` turns
/// false and the service falls back to UIImpactFeedbackGenerator. On device the
/// start fails often while the keyboard is still appearing, so a failure retries
/// in the background a few times before the fallback is kept until the next `warm()`.
// Engine state is confined to `queue`; `available` is guarded by `lock`.
final class KeyboardKeyHaptics: @unchecked Sendable {
    private static let idleStopDelay: TimeInterval = 120
    private static let startRetryDelay: TimeInterval = 0.5
    private static let startRetryLimit = 4

    private static let hardwareSupported = CHHapticEngine.capabilitiesForHardware().supportsHaptics

    private let queue = DispatchQueue(label: "app.songyan.keyboard.keyHaptics", qos: .userInteractive)
    private let lock = NSLock()
    private var available = KeyboardKeyHaptics.hardwareSupported
    // Confined to `queue`.
    private var engine: CHHapticEngine?
    private var player: CHHapticPatternPlayer?
    private var playerLevel: KeyboardFeedbackLevel?
    private var running = false
    private var idleStop: DispatchWorkItem?
    private var startRetry: DispatchWorkItem?
    private var startRetriesLeft = 0

    var isAvailable: Bool {
        lock.lock()
        defer { lock.unlock() }
        return available
    }

    private func setAvailable(_ value: Bool) {
        lock.lock()
        available = value
        lock.unlock()
    }

    /// Start the engine ahead of the first tap (keyboard appearance). Also clears an
    /// earlier failure so a transient error does not pin the fallback for the process.
    func warm() {
        guard Self.hardwareSupported else { return }
        setAvailable(true)
        queue.async {
            self.startRetriesLeft = Self.startRetryLimit
            guard self.startIfNeeded(level: nil) else { return }
            self.scheduleIdleStop()
        }
    }

    func play(level: KeyboardFeedbackLevel) {
        queue.async {
            guard self.startIfNeeded(level: level), let player = self.player else { return }
            do {
                try player.start(atTime: CHHapticTimeImmediate)
            } catch {
                // The server may have dropped the engine between taps; rebuild once.
                self.running = false
                self.player = nil
                self.playerLevel = nil
                if self.startIfNeeded(level: level), let player = self.player {
                    try? player.start(atTime: CHHapticTimeImmediate)
                }
            }
            self.scheduleIdleStop()
        }
    }

    func stop() {
        queue.async {
            self.cancelStartRetry()
            self.stopEngine()
        }
    }

    /// `level == nil` warms the engine without binding a pattern; a level change rebuilds the player.
    private func startIfNeeded(level: KeyboardFeedbackLevel?) -> Bool {
        if running, player != nil, level == nil || playerLevel == level { return true }
        do {
            let engine = try self.engine ?? makeEngine()
            self.engine = engine
            if !running {
                try engine.start()
                running = true
            }
            if let level, player == nil || playerLevel != level {
                let tap = CHHapticEvent(
                    eventType: .hapticTransient,
                    parameters: [
                        CHHapticEventParameter(parameterID: .hapticIntensity, value: level.hapticIntensity),
                        CHHapticEventParameter(parameterID: .hapticSharpness, value: level.hapticSharpness),
                    ], relativeTime: 0)
                player = try engine.makePlayer(with: CHHapticPattern(events: [tap], parameters: []))
                playerLevel = level
            }
            return true
        } catch {
            stopEngine()
            engine = nil
            setAvailable(false)
            scheduleStartRetry()
            return false
        }
    }

    private func scheduleStartRetry() {
        guard startRetry == nil, startRetriesLeft > 0 else { return }
        startRetriesLeft -= 1
        let item = DispatchWorkItem { [weak self] in
            guard let self else { return }
            self.startRetry = nil
            guard self.startIfNeeded(level: nil) else { return }
            self.setAvailable(true)
            self.scheduleIdleStop()
        }
        startRetry = item
        queue.asyncAfter(deadline: .now() + Self.startRetryDelay, execute: item)
    }

    private func cancelStartRetry() {
        startRetry?.cancel()
        startRetry = nil
        startRetriesLeft = 0
    }

    private func makeEngine() throws -> CHHapticEngine {
        let engine = try CHHapticEngine()
        engine.playsHapticsOnly = true
        // We stop it ourselves (idle / disappearance); auto-shutdown is what made
        // every tap after a pause a cold start.
        engine.isAutoShutdownEnabled = false
        engine.stoppedHandler = { [weak self] _ in
            guard let self else { return }
            self.queue.async { self.running = false }
        }
        engine.resetHandler = { [weak self] in
            guard let self else { return }
            // Players do not survive a server reset; the next tap rebuilds both.
            self.queue.async {
                self.running = false
                self.player = nil
                self.playerLevel = nil
            }
        }
        return engine
    }

    private func scheduleIdleStop() {
        idleStop?.cancel()
        let item = DispatchWorkItem { [weak self] in self?.stopEngine() }
        idleStop = item
        queue.asyncAfter(deadline: .now() + Self.idleStopDelay, execute: item)
    }

    private func stopEngine() {
        idleStop?.cancel()
        idleStop = nil
        guard running else { return }
        running = false
        engine?.stop(completionHandler: nil)
    }
}
